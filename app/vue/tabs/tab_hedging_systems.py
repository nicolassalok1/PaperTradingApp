def _format_suggestion_text(ref: str, suggestion: dict) -> str:
    side = str(suggestion.get("side") or "").lower()
    delta = float(suggestion.get("delta_qty", 0.0) or 0.0)
    action = "Buy" if side == "buy" else "Sell"
    qty_str = f"{delta:.2f}".rstrip("0").rstrip(".") if delta else "0"
    comment = suggestion.get("comment") or "Generated by DQN hedge prototype."
    return (
        f"{action} about {qty_str} contracts/shares to rebalance exposure for {ref}. "
        f"Note: {comment}"
    )


def _format_execution_text(ref: str, result: dict | str) -> str:
    if isinstance(result, dict):
        status = result.get("status") or result.get("message") or "sent"
        qty = result.get("qty") or result.get("quantity")
        side = str(result.get("side") or "").lower()
        action = "buy" if side == "buy" else "sell" if side else "trade"
        qty_part = f"{qty}" if qty is not None else "order"
        return f"Hedge {action} {qty_part} for {ref} {status}."
    return f"Hedge request for {ref}: {result}"


